"""Empirical coverage of the per-run confidence intervals, by occupancy tier."""

from __future__ import annotations

import argparse
import glob
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import norm

FRCNN = ["frcnn_resnet50", "frcnn_mobilenet"]
TIER_ORDER = ["full", "partial", "sparse", "rare"]

# display label -> (sampler, estimator, model scope).  Mirrors estimator_wins.CONFIGS plus
# the roster's model restriction (Table 1 of the paper).  NOTE the checkpoint parquets name
# the sampler generically (``importance`` / ``spotcheck`` / ``random``); it is the estimator
# that distinguishes DIS from AIS, so key on the pair.  The FRCNN ``dis``/``spotdis`` rows are
# the frozen-at-snapshot-0 diagnostic and are excluded by the "frozen" scope, as is the
# ``importance``-sampler difference/ratio/regression family, which the paper does not evaluate.
CONFIGS = {
    "Monte Carlo": ("random", "monte_carlo", "any"),
    "difference":  ("random", "difference", "any"),
    "ratio":       ("random", "ratio", "any"),
    "regression":  ("random", "regression", "any"),
    "DIS":         ("importance", "dis", "frozen"),
    "AIS":         ("importance", "ais", "frcnn"),
    "spotDIS":     ("spotcheck", "spotdis", "frozen"),
    "spotAIS":     ("spotcheck", "spotais", "frcnn"),
}
ROW_ORDER = list(CONFIGS)


def _require(checkpoint_dir: str) -> list:
    """Checkpoint parquets, or a clear error.  This cache is not shipped."""
    files = sorted(glob.glob(str(Path(checkpoint_dir) / "*.parquet")))
    if not files:
        raise SystemExit(
            f"no *.parquet under {checkpoint_dir!r} -- nothing to summarize.\n"
            "These per-checkpoint estimates are regenerated by "
            "`python3 analysis/derive_estimates.py`; run that first, "
            "or point --checkpoints at an existing directory.")
    return files


def load(checkpoint_dir: str, level: float) -> pd.DataFrame:
    """Per-cell coverage over the evaluated configurations."""
    z = norm.ppf(0.5 + level / 2.0)
    cols = ["estimator", "sampler", "model", "class_key", "checkpoint",
            "F_hat", "variance", "F_true"]
    want = {(s, e) for s, e, _ in CONFIGS.values()}
    scope = {(s, e): sc for s, e, sc in CONFIGS.values()}
    label = {(s, e): lab for lab, (s, e, _) in CONFIGS.items()}

    out = []
    for f in _require(checkpoint_dir):
        d = pd.read_parquet(f, columns=cols)
        d = d[[(s, e) in want for s, e in zip(d.sampler, d.estimator)]]
        d = d[d.variance.notna() & (d.variance > 0)]
        if d.empty:
            continue
        d["cfg"] = list(zip(d.sampler, d.estimator))
        d["label"] = d.cfg.map(label)
        is_frcnn = d.model.isin(FRCNN)
        sc = d.cfg.map(scope)
        keep = (sc == "any") | ((sc == "frcnn") & is_frcnn) | ((sc == "frozen") & ~is_frcnn)
        d = d[keep]
        if d.empty:
            continue
        half = z * np.sqrt(d.variance.to_numpy())
        hit = ((d.F_hat - half) <= d.F_true) & (d.F_true <= (d.F_hat + half))
        # interval half-width as a fraction of the true total: an interval can cover
        # simply by being wide, so width is reported alongside coverage.
        d = d.assign(hit=hit.astype(float), rel_half=half / d.F_true)
        out.append(d.groupby(["label", "class_key", "model", "checkpoint"])
                   .agg(coverage=("hit", "mean"), n_traj=("hit", "size"),
                        rel_half=("rel_half", "median")).reset_index())

    cov = pd.concat(out, ignore_index=True)
    # Monte Carlo ignores the model: the same uniform trajectories are replayed under every
    # model, so keep one representative per (class, budget) rather than 13 copies.
    mc = cov.label == "Monte Carlo"
    cov = pd.concat([cov[~mc],
                     cov[mc].sort_values("model")
                            .drop_duplicates(["label", "class_key", "checkpoint"])],
                    ignore_index=True)
    return cov


def summarize(cov: pd.DataFrame, level: float, agg: str = "mean") -> None:
    """``agg`` sets how per-cell coverages are pooled: ``mean`` (default; what the paper
    reports, and the probability that a randomly chosen run's interval covers) or ``median``."""
    cov = cov.copy()
    cov["tier"] = pd.Categorical(cov.tier, TIER_ORDER, ordered=True)
    spot = cov.label.isin(["spotDIS", "spotAIS"])

    print(f"nominal level: {level:.0%}   cells: {len(cov)}   "
          f"trajectories: {int(cov.n_traj.sum()):,}   pooling: {agg}\n")
    print(f"=== coverage by estimator x tier ({agg} over cells) ===")
    tab = (cov.groupby(["label", "tier"], observed=True).coverage.agg(agg)
           .unstack().reindex(index=ROW_ORDER, columns=TIER_ORDER))
    print(tab.round(3).to_string(), "\n")
    print("=== coverage by budget (excluding spot-check variants) ===")
    print(cov[~spot].groupby("checkpoint").coverage.agg(agg).round(3).to_string(), "\n")

    print("=== median CI half-width as a fraction of F_true, by estimator x tier ===")
    wid = (cov.groupby(["label", "tier"], observed=True).rel_half.median()
           .unstack().reindex(index=ROW_ORDER, columns=TIER_ORDER))
    print(wid.round(3).to_string(), "\n")
    print("=== median half-width by budget (excluding spot-check variants) ===")
    print(cov[~spot].groupby("checkpoint").rel_half.median().round(3).to_string(), "\n")
    print("=== headline ===")
    print(f"  all evaluated configs      mean {cov.coverage.mean():.3f}  "
          f"median {cov.coverage.median():.3f}")
    print(f"  excluding spotDIS/spotAIS  mean {cov[~spot].coverage.mean():.3f}  "
          f"median {cov[~spot].coverage.median():.3f}")
    print(f"  spotDIS/spotAIS only       mean {cov[spot].coverage.mean():.3f}  "
          f"median {cov[spot].coverage.median():.3f}")

    # Why the spot-check intervals fail: V_hat is right for the ensemble MEAN but far too
    # small for the TYPICAL run, because a few trajectories draw a tiny-q unit.
    print("\n=== V_hat skew across trajectories (mean/median), by estimator x tier ===")
    print(cov.pivot_table(index="label", columns="tier", values="vhat_skew",
                          aggfunc="median", observed=True)
          .reindex(index=ROW_ORDER, columns=TIER_ORDER).round(1).to_string())


def add_skew(cov: pd.DataFrame, checkpoint_dir: str) -> pd.DataFrame:
    """Attach mean(V_hat)/median(V_hat) per cell -- the diagnostic for why coverage fails."""
    cols = ["estimator", "sampler", "model", "class_key", "checkpoint", "variance"]
    want = {(s, e): lab for lab, (s, e, _) in CONFIGS.items()}
    rows = []
    for f in sorted(glob.glob(str(Path(checkpoint_dir) / "*.parquet"))):
        d = pd.read_parquet(f, columns=cols)
        d = d[[(s, e) in want for s, e in zip(d.sampler, d.estimator)]]
        d = d[d.variance.notna() & (d.variance > 0)]
        if d.empty:
            continue
        d["label"] = [want[(s, e)] for s, e in zip(d.sampler, d.estimator)]
        g = d.groupby(["label", "class_key", "model", "checkpoint"]).variance
        rows.append((g.mean() / g.median()).rename("vhat_skew").reset_index())
    return cov.merge(pd.concat(rows, ignore_index=True),
                     on=["label", "class_key", "model", "checkpoint"], how="left")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--checkpoints", default="outputs/analysis/checkpoints")
    ap.add_argument("--summary", default="outputs/analysis/estimates_summary.csv")
    ap.add_argument("--level", type=float, default=0.95, help="nominal CI level")
    ap.add_argument("--agg", choices=["mean", "median"], default="mean",
                    help="how per-cell coverages are pooled for the summary")
    ap.add_argument("--out", default="outputs/analysis/ci_coverage.csv")
    args = ap.parse_args()

    cov = load(args.checkpoints, args.level)
    summ = pd.read_csv(args.summary)
    summ.columns = [c.lstrip("﻿") for c in summ.columns]
    cov = cov.merge(summ[["class_key", "tier"]].drop_duplicates(), on="class_key")
    cov = add_skew(cov, args.checkpoints)
    cov.to_csv(args.out, index=False)
    summarize(cov, args.level, args.agg)
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
